package com.tk.eventmanager.model;

public enum EventStatus {
    DRAFT,       // Черновик — событие создаётся, но не видно пользователям
    PUBLISHED,   // Опубликовано — видно всем, можно регистрироваться
    CANCELED,    // Отменено — регистрация закрыта, уведомления разосланы
    COMPLETED,   // Завершено — событие прошло
    ARCHIVED     // Архив — для истории, не показывается в списках
}